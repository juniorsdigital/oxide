// Bundles the teaching interpreter (engine/*.js) into ui/rustlite.js as one factory function.
// The factory is serialised with Function.prototype.toString() to start a Web Worker, so it must stay self-contained.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const parts = ['parse.js', 'resolve.js', 'values.js', 'runtime.js', 'main.js'].map((f) => readFileSync(join(here, f), 'utf8'));
const out = '// Generated by engine/build.mjs from engine/*.js. Do not edit by hand.\n'
  + 'function RustLiteFactory() {\n"use strict";\n' + parts.join('\n') + '\n}\n'
  + 'if (typeof module !== "undefined") module.exports = RustLiteFactory;\n';
writeFileSync(join(here, '..', 'ui', 'rustlite.js'), out);
console.log('wrote ui/rustlite.js (' + out.length + ' bytes)');
